// Out of range is unlit.
inline constexpr bool mascot_pixel(const uint8_t* sprite, int x, int y) {
    if (x < 0 || y < 0 || x >= MASCOT_W || y >= MASCOT_H) return false;
    return (sprite[y * (MASCOT_W / 8) + (x >> 3)] & (0x80u >> (x & 7))) != 0;
}

