// ─── Line length and font, as compile errors — at runtime they fail silently ─────────────────────

namespace detail {

// The marks the help guide allows — fewer than the 5×5 font (`fonts/pt5x5.bdf`) draws. `'` and `;`
// draw blank.
constexpr bool help_char_ok(char c) {
    return (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c == ' ' ||
           c == ':' || c == '=' || c == '-' || c == '(' || c == ')' || c == '.' || c == '/' ||
           c == ',' || c == '+';
}

// One of the four arrows (U+2190..U+2193) at `s` — the only non-ASCII the font draws. Read a byte at
// a time, so a truncated sequence stops at the terminator.
constexpr bool help_arrow_at(const char* s) {
    if (static_cast<unsigned char>(s[0]) != 0xE2) return false;
    if (static_cast<unsigned char>(s[1]) != 0x86) return false;
    const auto tail = static_cast<unsigned char>(s[2]);
    return tail >= 0x90 && tail <= 0x93;
}

// Opens and closes a highlight in a body line; never drawn.
inline constexpr char HELP_MARK = '*';

// Columns `s[from, to)` takes on screen: an arrow is one, a highlight mark none.
constexpr int help_columns(const char* s, int from, int to) {
    int n = 0;
    for (int i = from; i < to;) {
        if (help_arrow_at(s + i)) { i += 3; ++n; continue; }
        if (s[i] != HELP_MARK) ++n;
        ++i;
    }
    return n;
}

// The budget is code points, not bytes: an arrow is one column. Only a body line may hold marks.
constexpr bool help_line_ok(const char* s, bool body = false) {
    if (s == nullptr) return true;   // an unwritten body line
    if (body && s[0] == '\n' && s[1] == '\0') return true;   // HELP_NEW_ROW
    int n = 0, marks = 0;
    for (int i = 0; s[i] != '\0';) {
        if (help_arrow_at(s + i)) { i += 3; ++n; continue; }
        if (body && s[i] == HELP_MARK) { ++marks; ++i; continue; }
        if (!help_char_ok(s[i])) return false;
        ++i;
        ++n;
    }
    return n <= HELP_MAX_CHARS && marks % 2 == 0;
}

constexpr bool help_table_ok() {
    for (const HelpEntry& e : HELP_ENTRIES) {
        if (!help_line_ok(e.line1) || !help_line_ok(e.line2) || !help_line_ok(e.line3)) return false;
        for (const char* b : e.body)
            if (!help_line_ok(b, true)) return false;
        for (const char* k : e.keys)
            if (!help_line_ok(k)) return false;
        for (const char* g : e.guide)
            if (!help_line_ok(g)) return false;
        for (const char* g : e.guideEmpty)
            if (!help_line_ok(g)) return false;
    }
    for (const GuideScreenLines& l : GUIDE_L)
        if (!help_line_ok(l.line[0]) || !help_line_ok(l.line[1])) return false;
    for (const char* const* pair : {GUIDE_R_NOWHERE, GUIDE_L_ELSEWHERE, GUIDE_SELECTION, GUIDE_LIVE, GUIDE_LIVE_L})
        if (!help_line_ok(pair[0]) || !help_line_ok(pair[1])) return false;
    return help_line_ok(GUIDE_R_TITLE) && help_line_ok(GUIDE_LIVE_TITLE) && help_line_ok(GUIDE_LIVE_R);
}

}  // namespace detail

// The title: `line1` up to its first colon, or all of it ("VOL: how loud…" → VOL).
// Counted in bytes, safe because a title never holds an arrow (`help_titles_ok`).
constexpr int help_title_length(const char* line1) {
    int n = 0;
    while (line1[n] != '\0' && line1[n] != ':') ++n;
    return n;
}

namespace detail {

// The length of the button name at `s` (A, START, D-PAD, an arrow…), or 0.
constexpr int help_button_at(const char* s) {
    if (help_arrow_at(s)) return 3;
    for (const char* name : {"START", "SELECT", "D-PAD", "A", "B", "L", "R", "X", "Y"}) {
        int n = 0;
        while (name[n] != '\0' && s[n] == name[n]) ++n;
        if (name[n] == '\0') return n;
    }
    return 0;
}

}  // namespace detail

// How many bytes at the front of a control-line word name buttons, so they can be drawn in their own
// colour: "A+B" → 3, "B," → 1 (the comma is not a button), "←CHAIN" → the arrow. 0 for "Add" or "a":
// a capital A that runs on into letters is a word, not the button.
constexpr int help_key_bytes(const char* word, int bytes) {
    int i = 0, keyEnd = 0;
    bool lastWasArrow = false;
    while (i < bytes) {
        const int n = detail::help_button_at(word + i);
        if (n == 0 || i + n > bytes) break;
        lastWasArrow = detail::help_arrow_at(word + i);
        i += n;
        keyEnd = i;
        if (i < bytes && (word[i] == '+' || word[i] == '/')) ++i;
        else break;
    }
    if (keyEnd == 0) return 0;
    for (int j = keyEnd; j < bytes; ++j)
        if (word[j] != ',' && word[j] != ':') return lastWasArrow ? keyEnd : 0;
    return keyEnd;
}

static_assert(help_key_bytes("A+B,", 4) == 3 && help_key_bytes("Add", 3) == 0 &&
              help_key_bytes("R+START", 7) == 7 && help_key_bytes("STARTS", 6) == 0 &&
              help_key_bytes("\xE2\x86\x90" "CHAIN", 8) == 3 && help_key_bytes("D-PAD", 5) == 5);

namespace detail {

constexpr bool help_titles_ok() {
    for (const HelpEntry& e : HELP_ENTRIES) {
        const int n = help_title_length(e.line1);
        if (n > HELP_TITLE_MAX_CHARS) return false;
        for (int i = 0; i < n; ++i)
            if (static_cast<unsigned char>(e.line1[i]) >= 0x80) return false;
    }
    return true;
}

}  // namespace detail

static_assert(sizeof(HELP_ENTRIES) / sizeof(HELP_ENTRIES[0]) ==
                  static_cast<size_t>(HelpTopic::COUNT),
              "HELP_ENTRIES has one entry per HelpTopic");
static_assert(detail::help_table_ok(),
              "a help line is over HELP_MAX_CHARS, or holds a mark the help guide does not allow "
              "(an apostrophe or a semicolon draws blank; the only non-ASCII are the four arrows; "
              "a * highlight only in the body, opened and closed on the same line)");
static_assert(detail::help_titles_ok(),
              "a help title (line1 up to its colon) is over HELP_TITLE_MAX_CHARS, or holds an arrow");

// Out of range gives the empty entry.
inline const HelpEntry& help_entry(HelpTopic topic) {
    const size_t i = static_cast<size_t>(topic);
    if (i >= static_cast<size_t>(HelpTopic::COUNT)) return HELP_ENTRIES[0];
    return HELP_ENTRIES[i];
}

