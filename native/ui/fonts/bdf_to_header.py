#!/usr/bin/env python3
"""Turns a BDF bitmap font into a C++ header the UI draws from: python3 bdf_to_header.py font.bdf

Writes `font.h` beside the .bdf. Run it by hand after editing a font; the build never runs Python.
The .bdf is the source: edit it in FontForge, Bits'N'Picas or a text editor, never the header.
"""

import os
import re
import sys

MAX_W = 16  # one uint16_t per glyph row


def parse(path):
    font = {"props": {}, "comments": [], "glyphs": []}
    glyph, bitmap = None, None
    for raw in open(path, encoding="latin-1"):
        line = raw.rstrip("\n")
        key, _, rest = line.partition(" ")
        if bitmap is not None and key != "ENDCHAR":
            bitmap.append(int(key, 16) if key else 0)
            continue
        if key == "COMMENT":
            font["comments"].append(rest)
        elif key in ("FAMILY_NAME", "COPYRIGHT", "NOTICE", "FONT_ASCENT", "FONT_DESCENT"):
            font["props"][key] = rest.strip().strip('"')
        elif key == "STARTCHAR":
            glyph = {}
        elif key == "ENCODING":
            glyph["cp"] = int(rest.split()[0])
        elif key == "DWIDTH":
            glyph["advance"] = int(rest.split()[0])
        elif key == "BBX":
            glyph["w"], glyph["h"], glyph["dx"], glyph["dy"] = (int(v) for v in rest.split())
        elif key == "BITMAP":
            bitmap = []
        elif key == "ENDCHAR":
            if glyph.get("cp", -1) >= 0:
                # Before the shift below, which a glyph wider than the table would make negative.
                if glyph["w"] > MAX_W:
                    sys.exit("%s: U+%04X is %d px wide; the table holds %d" % (path, glyph["cp"], glyph["w"], MAX_W))
                bits = 8 * ((glyph["w"] + 7) // 8)
                glyph["rows"] = [r >> (bits - glyph["w"]) << (MAX_W - glyph["w"]) for r in bitmap]
                font["glyphs"].append(glyph)
            glyph, bitmap = None, None
    return font


def check(font, path):
    for g in font["glyphs"]:
        where = "%s: U+%04X" % (path, g["cp"])
        if len(g["rows"]) != g["h"]:
            sys.exit("%s has %d bitmap rows for a box %d tall" % (where, len(g["rows"]), g["h"]))


def emit(font, path):
    stem = os.path.splitext(os.path.basename(path))[0]
    sym = re.sub(r"[^A-Za-z0-9]", "_", stem).upper()
    glyphs = sorted(font["glyphs"], key=lambda g: g["cp"])
    by_cp = {g["cp"]: i for i, g in enumerate(glyphs)}
    has_lower = any(ord("a") <= cp <= ord("z") for cp in by_cp)

    ascii_index = []
    for cp in range(128):
        if cp in by_cp:
            ascii_index.append(by_cp[cp])
        elif not has_lower and ord("a") <= cp <= ord("z") and cp - 32 in by_cp:
            ascii_index.append(by_cp[cp - 32])
        else:
            ascii_index.append(-1)

    space = by_cp.get(32)
    default_advance = glyphs[space]["advance"] if space is not None else max(g["advance"] for g in glyphs)

    rows, table = [], []
    for g in glyphs:
        table.append("    {0x%04X, %d, %d, %d, %d, %d, %d}," % (
            g["cp"], len(rows), g["w"], g["h"], g["dx"], g["dy"] + g["h"], g["advance"]))
        rows.extend(g["rows"])

    p = font["props"]
    out = ["#pragma once", "",
           "// Generated by bdf_to_header.py from %s — edit the .bdf and run it again." % os.path.basename(path)]
    out += ["// " + c for c in font["comments"]]
    out += ["", '#include "../bitmap_font.h"', "", "namespace pt::ui::fonts {", "",
            "inline constexpr uint16_t %s_ROWS[] = {" % sym]
    for i in range(0, len(rows), 12):
        out.append("    " + " ".join("0x%04X," % r for r in rows[i:i + 12]))
    out += ["};", "", "inline constexpr FontGlyph %s_GLYPHS[] = {" % sym]
    out += table
    out += ["};", "", "inline constexpr int16_t %s_ASCII[128] = {" % sym]
    for i in range(0, 128, 16):
        out.append("    " + " ".join("%d," % v for v in ascii_index[i:i + 16]))
    out += ["};", "",
            "inline constexpr BitmapFont %s = {" % sym,
            '    "%s", %s_ROWS, %s_GLYPHS, %d, %s_ASCII,' % (p.get("FAMILY_NAME", stem), sym, sym, len(glyphs), sym),
            "    %s, %s, %d, %s," % (p.get("FONT_ASCENT", 0), p.get("FONT_DESCENT", 0), default_advance,
                                     "true" if has_lower else "false"),
            "};", "", "}  // namespace pt::ui::fonts", ""]
    header = os.path.splitext(path)[0] + ".h"
    open(header, "w", encoding="utf-8").write("\n".join(out))
    print("%s: %d glyphs, %d rows%s" % (header, len(glyphs), len(rows), ", lowercase" if has_lower else ""))


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__.strip())
    for path in sys.argv[1:]:
        font = parse(path)
        check(font, path)
        emit(font, path)


if __name__ == "__main__":
    main()
